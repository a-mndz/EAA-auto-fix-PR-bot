/**
 * PR bot: renders fix results into a PR branch + comment with before/after
 * axe summary, scoped rule list, and explicit human-approval instructions.
 */

import type { FilePatch, ScanResult } from './types.js';
import {
  commitFiles,
  createBranch,
  createCheckRun,
  getHeadSha,
  openPullRequest,
  type RepoOctokit,
} from './github.js';

export interface PrPayload {
  owner: string;
  repo: string;
  baseBranch: string;
  branch: string;
  ruleIds: string[];
  patches: FilePatch[];
  beforeScan: ScanResult[];
  afterScan: ScanResult[];
  notes: string[];
  source: 'deterministic' | 'llm' | 'mixed';
  llmCostUsd: number;
}

export interface PrOutcome {
  prNumber: number;
  prUrl: string;
  branch: string;
}

function slugify(ruleIds: string[]): string {
  return ruleIds.slice(0, 3).join('-').slice(0, 48).replace(/[^a-z0-9-]/gi, '').toLowerCase();
}

export function branchName(ruleIds: string[]): string {
  return `eaa-fix/${slugify(ruleIds) || 'a11y'}`;
}

export function renderPrBody(payload: PrPayload): string {
  const before = payload.beforeScan.reduce((n, r) => n + r.violationCount, 0);
  const hasAfter = payload.afterScan.length > 0;
  const after = payload.afterScan.reduce((n, r) => n + r.violationCount, 0);
  const delta = after - before;

  const lines: string[] = [
    '## EAA accessibility fix',
    '',
    'Automated fix for detected axe-core violations. **A human must review and merge this PR — the bot cannot merge.**',
    '',
    '### Scope',
    ...payload.ruleIds.map((r) => `- axe rule: \`${r}\``),
    '',
    '### Before / after axe scan',
    '',
    '| URL | Before | After |',
    '| --- | ---: | ---: |',
  ];

  for (const b of payload.beforeScan) {
    const a = payload.afterScan.find((x) => x.url === b.url);
    lines.push(`| ${b.url} | ${b.violationCount} | ${a ? a.violationCount : 'pending'} |`);
  }
  if (hasAfter) {
    lines.push(
      '',
      `**Net change: ${delta > 0 ? `+${delta} (regression — do not merge)` : delta === 0 ? '0' : delta}** violations across scanned pages.`,
    );
  } else {
    lines.push(
      '',
      `Baseline: ${before} violation(s). The \`eaa-fix/rescan\` check runs after this PR opens and gates merge.`,
    );
  }
  lines.push(
    '',
    '### How this fix was generated',
    ...payload.notes.map((n) => `- ${n}`),
  );
  if (payload.llmCostUsd > 0) {
    lines.push(`- LLM cost: $${payload.llmCostUsd.toFixed(4)} (within per-fix cap)`);
  }
  lines.push(
    '',
    '### Review checklist',
    '1. Diff is limited to the listed axe rule IDs — no drive-by edits',
    '2. Visual layout unchanged (screenshots attached when configured)',
    '3. Re-scan check on this branch passes before merge',
    '',
    '> This PR was generated by an automated pipeline. The bot that opened it has **no merge permission**; merge is only possible after your approval.',
  );
  return lines.join('\n');
}

/** Create branch, commit patches, open PR, and attach the pre-merge check run. */
export async function publishFixPr(octokit: RepoOctokit, payload: PrPayload): Promise<PrOutcome> {
  const created = await createBranch(octokit, payload.owner, payload.repo, payload.branch, payload.baseBranch);
  if (!created) {
    throw new Error(`branch ${payload.branch} already exists; will not overwrite`);
  }

  await commitFiles(
    octokit,
    payload.owner,
    payload.repo,
    payload.branch,
    payload.patches,
    `fix(a11y): ${payload.ruleIds.join(', ')}`,
  );

  const headSha = await getHeadSha(octokit, payload.owner, payload.repo, payload.branch);
  const pr = await openPullRequest(octokit, payload.owner, payload.repo, {
    title: `fix(a11y): ${payload.ruleIds.join(', ')}`,
    body: renderPrBody(payload),
    head: payload.branch,
    base: payload.baseBranch,
  });

  if (payload.afterScan.length > 0) {
    const regression =
      payload.afterScan.reduce((n, r) => n + r.violationCount, 0) >
      payload.beforeScan.reduce((n, r) => n + r.violationCount, 0);
    await createCheckRun(octokit, payload.owner, payload.repo, {
      name: 'eaa-fix/rescan',
      headSha,
      status: 'completed',
      conclusion: regression ? 'failure' : 'success',
      title: regression ? 'Fix introduces new violations' : 'Re-scan clean',
      summary: regression
        ? 'The after-scan found more violations than the before-scan. Review required.'
        : 'After-scan did not increase the violation count.',
    });
  } else {
    await createCheckRun(octokit, payload.owner, payload.repo, {
      name: 'eaa-fix/rescan',
      headSha,
      status: 'in_progress',
      title: 'Re-scan pending',
      summary: 'The merge-gate re-scan runs after this PR is merged.',
    });
  }

  return { prNumber: pr.number, prUrl: pr.htmlUrl, branch: payload.branch };
}
